// Writes lib/src/render/paint/material_icon_codepoints.dart: every Material
// icon's codepoint in Flutter's MaterialIcons font, by its Flutter name
// (`lock`, `lock_rounded`, `lock_outlined`, `lock_sharp`), from the Flutter
// SDK's own icons.dart. Run after a Flutter upgrade:
//
//   dart run tool/gen_material_icon_codepoints.dart [path/to/flutter]
import 'dart:io';

void main(List<String> args) {
  final flutter = args.isNotEmpty ? args.first : '/opt/flutter';
  final source = File('$flutter/packages/flutter/lib/src/material/icons.dart').readAsStringSync();
  final entry = RegExp(r"static const IconData (\w+) = IconData\(\s*(0x[0-9a-fA-F]+),\s*fontFamily:\s*'MaterialIcons'");
  final names = <String, int>{};
  for (final m in entry.allMatches(source)) {
    names[m.group(1)!] = int.parse(m.group(2)!.substring(2), radix: 16);
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_material_icon_codepoints.dart from Flutter\'s')
    ..writeln('// icons.dart: do not edit. Each Material icon\'s codepoint in the')
    ..writeln('// MaterialIcons font, by its Flutter name (name, name_rounded,')
    ..writeln('// name_outlined, name_sharp). ${names.length} icons.')
    ..writeln('const Map<String, int> materialIconCodepoints = {');
  final keys = names.keys.toList()..sort();
  var line = StringBuffer('  ');
  for (final k in keys) {
    final item = "'$k': 0x${names[k]!.toRadixString(16)}, ";
    if (line.length + item.length > 118) {
      out.writeln(line.toString().trimRight());
      line = StringBuffer('  ');
    }
    line.write(item);
  }
  if (line.length > 2) out.writeln(line.toString().trimRight());
  out.writeln('};');
  File('lib/src/render/paint/material_icon_codepoints.dart').writeAsStringSync(out.toString());
  stdout.writeln('${names.length} icons');
}
