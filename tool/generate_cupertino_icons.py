"""Generates lib/src/utils/cupertino_icons_by_codepoint.dart.

Maps each CupertinoIcons codepoint to its const IconData so Cupertino icon
models can render with the cupertino_icons font while icon tree shaking still
works. Run with the Flutter SDK whose CupertinoIcons should be mirrored:

    python3 tool/generate_cupertino_icons.py /path/to/flutter
"""
import re
import sys
from pathlib import Path

flutter = Path(sys.argv[1] if len(sys.argv) > 1 else '/root/flutter')
source = (flutter / 'packages/flutter/lib/src/cupertino/icons.dart').read_text()

entries = {}
for match in re.finditer(
    r'static const IconData (\w+) = IconData\(\s*(0x[0-9a-fA-F]+)', source
):
    name, codepoint = match.group(1), int(match.group(2), 16)
    # Several names alias one glyph; the first declared name wins.
    entries.setdefault(codepoint, name)

lines = [
    '// GENERATED CODE - DO NOT MODIFY BY HAND.',
    '// Generated by tool/generate_cupertino_icons.py from Flutter\'s',
    '// CupertinoIcons.',
    '',
    "import 'package:flutter/cupertino.dart';",
    '',
    '/// Flutter\'s [CupertinoIcons] keyed by codepoint.',
    'const Map<int, IconData> cupertinoIconsByCodepoint = {',
]
for codepoint in sorted(entries):
    lines.append(f'  0x{codepoint:x}: CupertinoIcons.{entries[codepoint]},')
lines.append('};')
out = Path(__file__).resolve().parent.parent / 'lib/src/utils/cupertino_icons_by_codepoint.dart'
out.write_text('\n'.join(lines) + '\n')
print(f'{len(entries)} icons -> {out}')
