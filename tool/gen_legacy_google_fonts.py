"""Writes lib/src/utils/legacy_google_fonts.g.dart: TTF URLs for Google
Fonts families the editor offers (CodelesslyEditor's
lib/utils/google_fonts_metadata.dart) that the google_fonts package no
longer carries (Google merged width and optical-size families such as
"Roboto Condensed" and "Big Shoulders Stencil Display" into variable
fonts). The SDK loads these files itself.

    python3 tool/gen_legacy_google_fonts.py <google_fonts_metadata.dart> <google_fonts_all_parts.dart>
"""
import os
import re
import sys
import urllib.parse
import urllib.request

meta_src, pkg_src = sys.argv[1], sys.argv[2]
meta = open(meta_src).read()
pkg = open(pkg_src).read()
offered = re.findall(r"^  '([^']+)': <String, String>\{\n    'category': '[^']+',\n    'variants':\s*'([^']+)'", meta, re.M)
carried = set(re.findall(r"^    '([^']+)': Part\w\.\w+,$", pkg, re.M))
missing = [(f, v) for f, v in offered if f not in carried]
out = {}
for family, variants in missing:
    axes = []
    for v in variants.split(','):
        italic = 'i' in v.replace('regular', '')
        digits = re.match(r'\d+', v)
        axes.append((1 if italic else 0, int(digits.group(0)) if digits else 400))
    axes = sorted(set(axes))
    has_ital = any(i for i, _ in axes)
    spec = ('ital,wght@' + ';'.join(f'{i},{w}' for i, w in axes)) if has_ital else ('wght@' + ';'.join(str(w) for _, w in axes))
    url = 'https://fonts.googleapis.com/css2?family=' + urllib.parse.quote(family).replace('%20', '+') + ':' + spec
    try:
        css = urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'curl/8'}), timeout=30).read().decode()
    except Exception as e:
        print('skip', family, e)
        continue
    files = {}
    for block in re.findall(r'@font-face \{(.*?)\}', css, re.S):
        if 'unicode-range' in block and 'U+0000-00FF' not in block:
            continue
        style = re.search(r'font-style: (\w+)', block).group(1)
        weight = re.search(r'font-weight: (\d+)', block).group(1)
        src = re.search(r'url\((https://[^)]+\.ttf)\)', block)
        if src:
            files[f"{weight}{'italic' if style == 'italic' else ''}"] = src.group(1)
    if files:
        out[family] = files
        print(family, len(files))
here = os.path.dirname(os.path.abspath(__file__))
dst = os.path.join(here, '..', 'lib', 'src', 'utils', 'legacy_google_fonts.g.dart')
with open(dst, 'w') as f:
    f.write('// GENERATED by tool/gen_legacy_google_fonts.py. Do not edit.\n\n')
    f.write('/// TTF files of Google Fonts families that the google_fonts package no\n')
    f.write('/// longer carries, by family, then by weight (`400`, `700italic`, ...).\n')
    f.write('const Map<String, Map<String, String>> legacyGoogleFontFiles = {\n')
    for fam in sorted(out):
        f.write(f"  '{fam}': {{\n")
        for k in sorted(out[fam]):
            f.write(f"    '{k}': '{out[fam][k]}',\n")
        f.write('  },\n')
    f.write('};\n')
print('wrote', dst, len(out))
