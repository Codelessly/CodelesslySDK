#!/usr/bin/env python3
"""Writes lib/src/render/paint/material_icon_versions.dart: each Material
icon's latest version on fonts.gstatic.com, from Google Fonts' icon
metadata (https://fonts.google.com/metadata/icons). An icon's SVG lives at
.../materialicons<style>/<name>/v<version>/24px.svg and older versions are
not all kept, so an icon named in data (no version on the node) needs it.

  python3 tool/gen_material_icon_versions.py [metadata.json]
"""
import json, os, sys, urllib.request

src = sys.argv[1] if len(sys.argv) > 1 else None
raw = open(src).read() if src else urllib.request.urlopen('https://fonts.google.com/metadata/icons').read().decode()
icons = json.loads(raw[raw.index('{'):])['icons']
versions = {i['name']: i['version'] for i in icons if i['version'] != 1}
lines = ['// Generated by tool/gen_material_icon_versions.py. Do not edit.',
         '',
         '/// The latest version of each Material icon whose SVGs aren\'t at v1 on',
         '/// fonts.gstatic.com ([materialIconVersion] reads it; others are v1).',
         'const Map<String, int> materialIconVersions = {']
row = []
for name in sorted(versions):
    row.append(f"'{name}': {versions[name]}")
    if len(row) == 6:
        lines.append('  ' + ', '.join(row) + ',')
        row = []
if row: lines.append('  ' + ', '.join(row) + ',')
lines += ['};', '', '/// The version of Material icon [name] to load.',
          'int materialIconVersion(String name) => materialIconVersions[name] ?? 1;', '']
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lib', 'src', 'render', 'paint', 'material_icon_versions.dart')
open(out, 'w').write('\n'.join(lines))
print(len(versions), 'icons not at v1')
