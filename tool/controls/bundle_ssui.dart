// Bundles SSUI's tokens with the SDK: the `theme` of
// design_systems/ssui/design_system.json (the source) as a const map in
// lib/src/render/controls/ssui_defaults.g.dart, what an unstyled control
// draws with. test/controls/tokens_test.dart fails when the two differ.
//
//   dart run tool/controls/bundle_ssui.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final source = jsonDecode(File('design_systems/ssui/design_system.json').readAsStringSync()) as Map<String, Object?>;
  final theme = source['theme'];
  final out = StringBuffer()
    ..writeln('// Generated by tool/controls/bundle_ssui.dart from design_systems/ssui/design_system.json. Do not edit.')
    ..writeln('//')
    ..writeln('// SSUI\'s theme: the tokens an unstyled control draws with (lib/src/render/controls/tokens.dart).')
    ..writeln('// ignore_for_file: prefer_single_quotes')
    ..writeln()
    ..writeln('/// The `theme` of SSUI\'s design_system.json (version ${source['version']}).')
    ..writeln('const Map<String, Object?> ssuiTheme = ${_dart(theme, 0)};');
  File('lib/src/render/controls/ssui_defaults.g.dart').writeAsStringSync(out.toString());
}

String _dart(Object? v, int depth) {
  final pad = '  ' * (depth + 1), end = '  ' * depth;
  if (v is Map) {
    if (v.isEmpty) return '<String, Object?>{}';
    return '{\n${v.entries.map((e) => '$pad${jsonEncode(e.key)}: ${_dart(e.value, depth + 1)}').join(',\n')},\n$end}';
  }
  if (v is List) {
    if (v.isEmpty) return '<Object?>[]';
    return '[\n${v.map((e) => '$pad${_dart(e, depth + 1)}').join(',\n')},\n$end]';
  }
  if (v is String) return jsonEncode(v).replaceAll(r'$', r'\$');
  return jsonEncode(v);
}
