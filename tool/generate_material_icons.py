"""Generates lib/src/utils/material_icons_by_name.dart.

Maps each Material icon's styled name (`play_arrow`, `play_arrow_rounded`,
`home_outlined`, ...) to Flutter's const [Icons] entry. Icon models store the
codepoints of Google's Material Icons fonts, which differ from the codepoints
of Flutter's bundled MaterialIcons font (play_arrow is 0xe037 in Google's
fonts and 0xe4cb in Flutter's), so the SDK finds Flutter's glyph by name.
Run with the Flutter SDK whose Icons should be mirrored:

    python3 tool/generate_material_icons.py /path/to/flutter
"""
import re
import sys
from pathlib import Path

flutter = Path(sys.argv[1] if len(sys.argv) > 1 else '/opt/flutter')
source = (flutter / 'packages/flutter/lib/src/material/icons.dart').read_text()

# Each entry's doc comment names the icon as Google's fonts do, e.g.
# `<i class="material-icons-round md-36">10k</i>` above `ten_k_rounded`.
styles = {'material-icons': '', 'material-icons-outlined': '_outlined',
          'material-icons-round': '_rounded', 'material-icons-sharp': '_sharp'}
names = {}
for match in re.finditer(
    r'<i class="(material-icons[a-z-]*) md-36">(\w+)</i>[^\n]*\n\s*static const IconData (\w+) = IconData\(',
    source,
):
    style, google, flutter_name = match.groups()
    if style in styles:
        names.setdefault(google + styles[style], flutter_name)

lines = [
    '// GENERATED CODE - DO NOT MODIFY BY HAND.',
    "// Generated by tool/generate_material_icons.py from Flutter's Icons.",
    '',
    "import 'package:flutter/material.dart';",
    '',
    "/// Flutter's [Icons] keyed by styled name: the icon's name, plus",
    '/// `_outlined`, `_rounded` or `_sharp` for those styles.',
    'const Map<String, IconData> materialIconsByName = {',
]
for key, name in names.items():
    lines.append(f"  '{key}': Icons.{name},")
lines.append('};')
out = Path(__file__).resolve().parent.parent / 'lib/src/utils/material_icons_by_name.dart'
out.write_text('\n'.join(lines) + '\n')
print(f'{len(names)} icons -> {out}')
